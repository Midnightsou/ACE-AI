// Map tool IDs to their icons
export function ToolIcon({ toolId, size = 18, className = '' }) {
  const icons = {
    'chat': ChatIcon,
    'codex': CodexIcon,
    'math': MathIcon,
    'cv-maker': CVIcon,
    'cv-analyser': CVIcon,
    'cover-letter': CoverLetterIcon,
    'essay-writer': EssayIcon,
    'email-composer': EmailIcon,
    'dojo': DojoIcon,
  }
  const Icon = icons[toolId] || ChatIcon
  return <Icon size={size} className={className} />
}